def fmt_gib(b: float) -> str:
    return f"{b / GiB:.2f}"


def write_tex(name: str, body: str) -> Path:
    GEN.mkdir(parents=True, exist_ok=True)
    p = GEN / name
    p.write_text(f"% Generated by hostoffload.analysis.pipeline. Do not edit.\n{body}")
    return p


def table(caption: str, label: str, header: list[str], rows: list[list[str]], align: str, note: str = "",
          size: str = "\\small", placement: str = "t", landscape: bool = False) -> str:
    # fittable (paper/main.tex) logs the natural width and shrinks a table only when it is wider than the text
    # block; tables that would shrink a lot are split into upright parts by their callers rather than set landscape
    env = "sidewaystable" if landscape else "table"
    lines = [f"\\begin{{{env}}}" + ("" if landscape else f"[{placement}]"), "\\centering", size,
             f"\\begin{{fittable}}{{{label}}}", f"\\begin{{tabular}}{{{align}}}", "\\toprule",
             " & ".join(header) + " \\\\", "\\midrule"]
    # a str row is a group heading that spans the table (e.g. one variant of a concurrency table)
    lines += [f"\\addlinespace\\multicolumn{{{len(header)}}}{{l}}{{{r}}} \\\\" if isinstance(r, str)
              else " & ".join(r) + " \\\\" for r in rows]
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{fittable}"]
    if note:
        lines.append(f"\\par\\smallskip\\parbox{{0.95\\linewidth}}{{\\footnotesize\\raggedright {note}}}")
    lines += [f"\\caption{{{caption}}}", f"\\label{{{label}}}", f"\\end{{{env}}}", ""]
    return "\n".join(lines)



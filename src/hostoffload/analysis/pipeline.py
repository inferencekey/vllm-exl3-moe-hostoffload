    reg.put("expl.model_loading_gib", sl["model_loading_gib_by_rank"][0], [sweep_log], E, "{:.2f}")
    reg.put("expl.model_loading_s", sl["model_loading_s_by_rank"][0], [sweep_log], E, "{:.0f}")

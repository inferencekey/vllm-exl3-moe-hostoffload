def exploratory_section(reg: Registry) -> None:
    E = "exploratory"
    sweep_log = X.SWEEP / "logs" / "serve.log"
    first_log = X.FIRST / "results" / "agent30" / "serve.log"
    long_log = X.SWEEP / "logs" / "serve_maxlen1048576.log"

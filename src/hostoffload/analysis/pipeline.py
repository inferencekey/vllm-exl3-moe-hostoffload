    reg.put("expl.engram_pinned_gib", sl["engram_pinned_gib_total"], [sweep_log], E, "{:.1f}")
    reg.put("expl.engram_per_table_rank_gib", sl["engram_tables"][0]["gib"], [sweep_log], E, "{:.2f}")
    ll = serve_log.parse_file(long_log)
    reg.put("expl.1m.kv_tokens", ll["kv_cache_tokens"], [long_log], E, "{:,}")
    reg.put("expl.1m.model_loading_gib", ll["model_loading_gib_by_rank"][0], [long_log], E, "{:.2f}")
    reg.put("expl.1m.cuda_graph_gib", ll["cuda_graph_gib_by_rank"][0], [long_log], E, "{:.2f}")
    if plans_dir.exists():
        from ..weights.split import load_plan
        plans = {n: load_plan(plans_dir / f"plan-{n}-dh.json") for n in ("agent30", "gen30", "blend30")}
        for key, log in (("sweep", sweep_log), ("first", first_log)):
            match = serve_log.identify_plan(serve_log.parse_file(log), plans)
            if len(match) == 1:
                reg.put(f"expl.plan_identified.{key}", match[0], [log, *(plans_dir / f"plan-{n}-dh.json"
                                                                       for n in plans)], E,
                        note="per-layer host-expert counts logged by the server equal this plan's on all layers")

    # memory peaks from the 5 s sampler
    mem = X.SWEEP / "results" / "mem_samples.csv"
    peaks = X.mem_peaks_by_level()
    reg.put("expl.vram_peak_mib", max(max(p["vram_gpu0_mib"], p["vram_gpu1_mib"]) for p in peaks), [mem], E,
            "{:,.0f}")
    reg.put("expl.vram_min_peak_mib", min(min(p["vram_gpu0_mib"], p["vram_gpu1_mib"]) for p in peaks), [mem], E,
            "{:,.0f}")
    reg.put("expl.ram_anon_max_gib", max(p["ram_anon_gib"] for p in peaks), [mem], E, "{:.1f}")
    reg.put("expl.ram_anon_min_gib", min(p["ram_anon_gib"] for p in peaks), [mem], E, "{:.1f}")
    reg.put("expl.ram_shmem_gib", max(p["ram_shmem_gib"] for p in peaks), [mem], E, "{:.1f}")
    reg.put("expl.ram_current_max_gib", max(p["ram_current_gib"] for p in peaks), [mem], E, "{:.1f}")
    # feasibility arithmetic calibrated on the exploratory boot (labelled exploratory)
    fa = X.sweep_file("A")
    total_mib = next(g[2] for s in X.load_sweep("A")["samples"]["1"] if s.get("gpus") for g in s["gpus"])
    reg.put("expl.gpu_total_mib", total_mib, [fa], E, "{:,.0f}")
    reg.put("expl.gpu_total_gib", total_mib / 1024, [fa], E, "{:.1f}")
    # how far the pack without a plan overshoots one card (file bytes per GPU against the card's reported total)
    nop_vram = json.loads(PLACEMENT.read_text())["placements"]["no_plan"]["totals"].get("vram", 0)
    reg.put("expl.noplan_over_per_gpu_gib", nop_vram / GiB / 2 - total_mib / 1024, [fa, PLACEMENT], E, "{:.1f}")
    ms = X.SWEEP / "logs" / "memory_startup.txt"
    lines = ms.read_text().splitlines()
    cg = int(lines[lines.index("== cgroup") + 1])  # first line after the header is memory.max
    reg.put("expl.cgroup_max_gib", cg / GiB, [ms], E, "{:.1f}")
    for sc in ("A", "B"):
        lv = {r["N"]: r for r in X.level_rows(sc)}
        reg.put(f"expl.{sc}.agg_ratio_64_1", lv[64]["aggregate_out_tok_s"] / lv[1]["aggregate_out_tok_s"],
                [X.sweep_file(sc)], E, "{:.1f}")
        reg.put(f"expl.{sc}.agg_ratio_8_1", lv[8]["aggregate_out_tok_s"] / lv[1]["aggregate_out_tok_s"],
                [X.sweep_file(sc)], E, "{:.1f}")
        reg.put(f"expl.{sc}.errors_total", sum(r["errors"] for r in lv.values()), [X.sweep_file(sc)], E)
        reg.put(f"expl.{sc}.requests_total", sum(r["ok"] for r in lv.values()), [X.sweep_file(sc)], E)
    headroom_mib = total_mib - max(max(p["vram_gpu0_mib"], p["vram_gpu1_mib"]) for p in peaks)
    reg.put("expl.headroom_mib", headroom_mib, [fa, mem], E, "{:,.0f}")
    pl = json.loads(PLACEMENT.read_text())
    gen = pl["placements"]["plan-gen30-dh"]
    runtime_overhead = sl["model_loading_gib_by_rank"][0] - gen["totals"]["vram"] / GiB / 2

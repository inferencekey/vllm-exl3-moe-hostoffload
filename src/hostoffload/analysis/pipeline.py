    reg.put("hub.orig.license", ho["license"], [hub_orig], "static")
    hub_pack = STATIC / "hub" / "diffbot__DeepSeek-V4.1-Flash-EXL3-3bpw-2x-RTX-PRO-6000@a1cf1bd2.json"
    reg.put("hub.pack.license", json.loads(hub_pack.read_text())["license"], [hub_pack], "static")
    # budgets of the prepared plans (same arithmetic as experiments/tools/make_plan_md.py)
    from ..cost import plan_budget
    ef, pf = ROOT / "experiments" / "experiments.yaml", ROOT / "experiments" / "pricing.yaml"
    ecfg, pricing = plan_budget.load()
    fm = plan_budget.full_and_minimal(ecfg, pricing)
    reg.put("plan.full_usd", fm["full_usd"], [ef, pf], "static", "{:.0f}")
    reg.put("plan.minimal_usd", fm["minimal_usd"], [ef, pf], "static", "{:.0f}")
    reg.put("plan.full_usd_cont", fm["full_usd_cont"], [ef, pf], "static", "{:.0f}")
    reg.put("plan.minimal_usd_cont", fm["minimal_usd_cont"], [ef, pf], "static", "{:.0f}")
    reg.put("plan.contingency_pct", 100 * fm["contingency"], [ef], "static", "{:.0f}")
    reg.put("plan.full_hours", fm["full_hours"], [ef], "static", "{:.1f}")
    ln = plan_budget.lean(ecfg, pricing)
    for k, fmt in (("core_minutes", "{:.0f}"), ("all_minutes", "{:.0f}"), ("core_usd", "{:.2f}"),
                   ("all_usd", "{:.2f}"), ("core_minutes_cont", "{:.0f}"), ("core_usd_cont", "{:.2f}"),
                   ("all_usd_cont", "{:.2f}"), ("hard_cap_usd", "{:.2f}"), ("hard_cap_minutes", "{:.0f}"),
                   ("soft_cap_usd", "{:.2f}"), ("soft_cap_minutes", "{:.0f}"), ("watchdog_seconds", "{:,}")):
        reg.put(f"lean.{k}", ln[k], [ef, pf], "static", fmt)
    reg.put("lean.api_usd_peak", ln["api"]["usd_peak"], [ef, pf, STATIC / "pricing" / "deepseek-api-pricing-2026-10-06.html"],
            "static", "{:.2f}", note="estimated token counts x published price")
    reg.put("lean.api_usd_off_peak", ln["api"]["usd_off_peak"], [ef, pf], "static", "{:.2f}")
    api = pricing["api"]["deepseek-flash"]
    reg.put("api.price_out_peak", api["peak"]["output"], [pf], "static", "{:.2f}")
    reg.put("api.price_in_peak", api["peak"]["input_cache_miss"], [pf], "static", "{:.2f}")

    rows = []
    for cls, label in CLASS_LABELS:
        a = nop["by_class"].get(cls, {})
        g = gen["by_class"].get(cls, {})
        o = po["placements"]["no_plan"]["by_class"].get(cls, {})
        rows.append([label, fmt_gib(sum(o.values())), fmt_gib(sum(a.values())),
                     fmt_gib(g.get("vram", 0)), fmt_gib(g.get("host", 0)),
                     "not loaded" if "not_loaded" in g else ""])
    rows.append(["\\textbf{total}", fmt_gib(po["total_file_bytes"]), fmt_gib(pl["total_file_bytes"]),
                 fmt_gib(gen["totals"].get("vram", 0)), fmt_gib(gen["totals"].get("host", 0)),
                 fmt_gib(gen["totals"].get("not_loaded", 0))])
    write_tex("static_placement.tex", table(
        "Checkpoint bytes by tensor class (GiB, from safetensors headers) for DeepSeek's original checkpoint and the "
        "served EXL3 pack, and where the pack's bytes go under the \\texttt{gen30} host-expert plan with the "
        "documented placement rules (text-only serving). File bytes, not runtime allocations. Static measurement.",
        "tab:static-placement", ["tensor class", "original", "EXL3 pack", "VRAM", "host", "other"],
        rows, "lrrrrr",
        note=f"Sources: \\texttt{{{latex_escape(rel(PLACEMENT_ORIG))}}}, \\texttt{{{latex_escape(rel(PLACEMENT))}}}."))
    reg.artifact("static_placement.tex", "static", [PLACEMENT, PLACEMENT_ORIG], "data")
    F.placement_bars([(lab, g.get("vram", 0) / GiB, g.get("host", 0) / GiB) for cls, lab in CLASS_LABELS[:6]
                      for g in [gen["by_class"].get(cls, {})]], FIG / "static_placement.pdf",
                     "EXL3 pack under the gen30 plan (static)")
    reg.artifact("figures/generated/static_placement.pdf", "static", [PLACEMENT], "data")
    F.host_experts_per_layer(sorted((int(k), v) for k, v in gen["host_experts_per_layer"].items()),
                             FIG / "static_host_per_layer.pdf", "gen30: experts kept in host memory per layer")
    reg.artifact("figures/generated/static_host_per_layer.pdf", "static", [PLACEMENT], "data")



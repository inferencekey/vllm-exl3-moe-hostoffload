def api_usage_cost(usage_file: Path, price: dict) -> dict:
    """Real token counts from quality/api_proxy.py's usage log, priced with the published per-1M rates."""
    rows = [json.loads(line) for line in usage_file.read_text().splitlines() if line.strip()]
    us = [r["usage"] for r in rows if r.get("usage")]
    miss = sum(u.get("prompt_cache_miss_tokens", u["prompt_tokens"]) for u in us)
    hit = sum(u.get("prompt_cache_hit_tokens", 0) for u in us)
    out = sum(u["completion_tokens"] for u in us)
    usd = (miss * price["input_cache_miss"] + hit * price["input_cache_hit"] + out * price["output"]) / 1e6
    return {"requests": len(rows), "ok": sum(r.get("status") == 200 for r in rows), "input_miss": miss,
            "input_hit": hit, "output": out, "usd": usd}


def quality_paired_table(e10: Path, e11: Path, reg: Registry) -> str:
    """Item-paired comparison of the measured stack (E10) against the reference (E11) on the items both answered."""
    from . import quality as Q
    rows = []
    for task, metric in QUALITY_METRICS.items():
        a, b = Q.load_samples(e11, task, metric), Q.load_samples(e10, task, metric)
        r = Q.paired_difference(a, b)
        if r is None:
            continue
        key = f"ctl.Q.{task}"
        srcs = sorted(e10.rglob(f"samples_{task}_*.jsonl")) + sorted(e11.rglob(f"samples_{task}_*.jsonl"))
        reg.put(f"{key}.n", r["n"], srcs, "controlled", "{:,}")
        reg.put(f"{key}.diff", r["diff"], srcs, "controlled", "{:+.3f}", note="E10 minus E11, paired items")
        reg.put(f"{key}.ci_lo", r["ci95"][0], srcs, "controlled", "{:+.3f}")
        reg.put(f"{key}.ci_hi", r["ci95"][1], srcs, "controlled", "{:+.3f}")
        reg.put(f"{key}.flips_pct", 100 * r["discordant"] / r["n"], srcs, "controlled", "{:.1f}")
        rows.append([latex_escape(task), latex_escape(metric), str(r["n"]), f"{r['mean_b']:.3f}", f"{r['mean_a']:.3f}",
                     f"{r['diff']:+.3f}", f"[{r['ci95'][0]:+.3f}, {r['ci95'][1]:+.3f}]",
                     f"{100 * r['discordant'] / r['n']:.1f}"])
    return table("Controlled: EXL3 stack (E10) against the API reference (E11) on the same items. Difference E10 minus "
                 "E11 with a paired percentile bootstrap 95\\% interval (5000 resamples); flips are items whose outcome "
                 "differs. The reference is a different serving stack, so a difference is not attributable to "
                 "quantization alone.", "tab:ctl-quality-paired",
                 ["task", "metric", "$n$", "E10", "E11", "diff.", "95\\% CI", "flips \\%"], rows, "llrrrrlr")



    reg.put("static.target_experts", sum(v for k, v in nop["experts_per_layer"].items() if int(k) < 40), src,
            "static", "{:,}")
    reg.put("static.expert_mib", nop["expert_bytes_max"] / 2**20, src, "static", "{:.2f}")
    reg.put("static.orig.expert_mib", po["placements"]["no_plan"]["expert_bytes_max"] / 2**20, srco, "static",
            "{:.2f}")
    for cls in ("routed_expert", "engram_table", "drafter_routed_expert", "embedding", "attention"):
        reg.put(f"static.pack.{cls}_gib", sum(nop["by_class"][cls].values()) / GiB, src, "static", "{:.2f}")
        reg.put(f"static.orig.{cls}_gib", sum(po["placements"]["no_plan"]["by_class"][cls].values()) / GiB, srco,
                "static", "{:.2f}")
    for name, p in (("noplan", nop), ("gen30", gen)):
        reg.put(f"static.{name}.vram_gib", p["totals"].get("vram", 0) / GiB, src, "static", "{:.1f}")
        reg.put(f"static.{name}.host_gib", p["totals"].get("host", 0) / GiB, src, "static", "{:.1f}")
        reg.put(f"static.{name}.vram_per_gpu_gib", p["totals"].get("vram", 0) / GiB / 2, src, "static", "{:.1f}")
    reg.put("static.gen30.host_experts", gen["host_experts_total"], src, "static", "{:,}")
    reg.put("static.gen30.host_target_experts", sum(v for k, v in gen["host_experts_per_layer"].items()
                                                    if int(k) < 40), src, "static", "{:,}")
    reg.put("static.gen30.host_expert_gib", (gen["by_class"]["routed_expert"].get("host", 0) +
                                             gen["by_class"]["drafter_routed_expert"].get("host", 0)) / GiB, src,
            "static", "{:.1f}")
    host_target = sum(v for k, v in gen["host_experts_per_layer"].items() if int(k) < 40)
    all_target = sum(v for k, v in nop["experts_per_layer"].items() if int(k) < 40)
    reg.put("static.gen30.host_target_share_pct", 100 * host_target / all_target, src, "static", "{:.0f}")
    per_layer = [int(v) for k, v in gen["host_experts_per_layer"].items() if int(k) < 40]
    reg.put("static.gen30.host_per_layer_min", min(per_layer), src, "static")
    reg.put("static.gen30.host_per_layer_max", max(per_layer), src, "static")
    orig_dense_experts = sum(sum(v.values()) for k, v in po["placements"]["no_plan"]["by_class"].items()
                             if k not in ("engram_table", "embedding", "vision"))
    reg.put("static.orig.vram_min_gib", orig_dense_experts / GiB, srco, "static", "{:.1f}",
            note="original checkpoint bytes that must be GPU-resident or offloaded: everything except Engram "
                 "tables, embedding and vision")

    cfg_file = STATIC / "hub" / "diffbot__DeepSeek-V4.1-Flash-EXL3-3bpw-2x-RTX-PRO-6000@a1cf1bd2.config.json"
    c = json.loads(cfg_file.read_text())
    tc = c["text_config"]
    for k in ("num_hidden_layers", "n_routed_experts", "num_experts_per_tok", "hidden_size", "moe_intermediate_size",
              "n_shared_experts", "sliding_window", "index_topk"):
        reg.put(f"cfg.{k}", tc[k], [cfg_file], "static", "{:,}")
    reg.put("cfg.max_position_embeddings", tc["max_position_embeddings"], [cfg_file], "static", "{:,}")
    reg.put("cfg.engram_layers", ", ".join(str(x) for x in tc["engram_layer_ids"]), [cfg_file], "static")
    reg.put("cfg.engram_tables", len(tc["engram_layer_ids"]), [cfg_file], "static")
    reg.put("cfg.exl3_bits", c["quantization_config"]["bits"], [cfg_file], "static")
    hub_orig = STATIC / "hub" / "deepseek-ai__DeepSeek-V4.1-Flash@2cba9e42.json"
    ho = json.loads(hub_orig.read_text())

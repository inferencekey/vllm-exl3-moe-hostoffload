SESSION_FILES = ("session.json", "session2.json", "session3.json")  # pod session 1, 2, 3 under data/controlled/LEAN


def pod_of(run: Path) -> str:
    """Pod session (1, 2, 3) whose create-to-delete window contains the run folder's UTC timestamp, or '?'."""
    from datetime import datetime, timezone
    try:
        t = datetime.strptime(run.name, "%Y%m%dT%H%M%SZ").replace(tzinfo=timezone.utc)
    except ValueError:
        return "?"
    for i, name in enumerate(SESSION_FILES, 1):
        f = ROOT / "data" / "controlled" / "LEAN" / name
        if not f.exists():
            continue
        sj = json.loads(f.read_text())
        t0, t1 = (datetime.strptime(sj[k], "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
                  for k in ("created_utc", "deleted_utc"))
        if t0 <= t <= t1:
            return str(i)
    return "?"


def controlled_concurrency_table(exp: dict, runs: list[Path], reg: Registry, slos: dict) -> str:
    """Pooled-over-repetitions summary per (scenario, load point) with across-repetition CV and SLO flags."""
    groups: dict[tuple[str, str, str], dict[int, list[dict]]] = {}
    pods: dict[str, set[str]] = {}
    for run in runs:
        variant = run.parent.name
        pods.setdefault(variant, set()).add(pod_of(run))
        for line in (run / "requests.jsonl").read_text().splitlines():
            r = json.loads(line)
            if r["level"] == "warm":
                continue
            groups.setdefault((variant, r["scenario"], r["level"]), {}).setdefault(r["repetition"], []).append(r)
    lat, thr, current = [], [], None
    srcs = [run / "requests.jsonl" for run in runs]
    def natural(t: str) -> tuple:  # prefill-4096 before prefill-16384
        return tuple(int(x) if x.isdigit() else x for x in re.split(r"(\d+)", t))

    def load_key(k):  # closed:2 before closed:16
        mode, _, v = k[2].partition(":")
        return (k[0], natural(k[1]), mode, float(v) if v.replace(".", "", 1).isdigit() else 0.0, v)
    for (variant, scen, level), reps in sorted(groups.items(), key=lambda kv: load_key(kv[0])):
        pooled = level_summary([r for rs in reps.values() for r in rs])
        per_rep = [level_summary(rs) for rs in reps.values()]
        tpot_med = [(s.get("tpot_s") or {}).get("p50") for s in per_rep]
        agg = [s.get("aggregate_out_tok_s_window") for s in per_rep]
        rs = stats.repetition_summary([x for x in agg if x is not None])
        ok_all = {name: all(meets_sla(s, slo) for s in per_rep) and meets_sla(pooled, slo)
                  for name, slo in slos.items()}
        key = f"ctl.{exp['id']}.{variant}.{scen}.{level}".replace(" ", "")
        t = pooled.get("ttft_s") or {}
        tp = pooled.get("tpot_s") or {}
        e2e = pooled.get("e2e_s") or {}
        for k, v in (("ttft_p50", t.get("p50")), ("ttft_p95", t.get("p95")), ("ttft_p99", t.get("p99")),
                     ("tpot_p50", tp.get("p50")), ("tpot_p95", tp.get("p95")), ("e2e_p50", e2e.get("p50")),
                     ("e2e_p99", e2e.get("p99")), ("agg_mean", rs.get("mean")), ("agg_cv", rs.get("cv"))):
            if v is not None:
                if k.startswith("tpot"):  # seconds in the data, milliseconds in the text
                    reg.put(f"{key}.{k}_ms", 1000 * v, srcs, "controlled", "{:.1f}")
                fmt = {"agg_mean": "{:.0f}", "agg_cv": "{:.2f}"}.get(k, "{:.2f}")
                reg.put(f"{key}.{k}", v, srcs, "controlled", fmt)
                if k == "agg_mean" and v > 1:  # output-only attribution: the whole pod hour charged to output tokens
                    pf = ROOT / "experiments" / "pricing.yaml"
                    usd_h = yaml.safe_load(pf.read_text())["configs"]["2x-rtx-pro-6000"]["usd_per_hour"]
                    reg.put(f"{key}.usd_per_m_out", usd_h / (v * 3600) * 1e6, srcs + [pf], "controlled", "{:.2f}")
        if variant != current:  # variant and pod head their block of rows in both parts
            current = variant
            pod = ",".join(sorted(pods[variant]))
            head = f"\\textit{{{latex_escape(variant)}}}, pod {pod}"
            lat.append(head)
            thr.append(head)
        lat.append([latex_escape(scen), latex_escape(level), str(pooled["n"]),
                    f"{t.get('p50', 0):.2f}", f"{t.get('p95', 0):.2f}", f"{t.get('p99', 0):.2f}",
                    f"{1000 * (tp.get('p50') or 0):.1f}", f"{1000 * (tp.get('p95') or 0):.1f}",
                    f"{e2e.get('p50', 0):.1f}", f"{e2e.get('p99', 0):.1f}"])
        thr.append([latex_escape(scen), latex_escape(level), str(len(reps)), str(pooled["n"]),
                    f"{rs.get('mean') or 0:.1f}", f"{100 * (rs.get('cv') or 0):.1f}" if len(reps) > 1 else "-",
                    ",".join(n[0] for n, ok in ok_all.items() if ok) or "-"])
        _ = tpot_med
    # The caption describes what ran (table_title in experiments.yaml), not the designed protocol (title).
    title = exp.get("table_title", exp["title"])
    # Split in two upright tables: what each request sees (latency) and what the server delivers (throughput, SLOs).
    lab = f"tab:ctl-{exp['id']}"
    return (table(f"Controlled: {latex_escape(title)}. Part 1 of 2, per-request latency: time to first token "
                  "(TTFT, s), time per output token (TPOT, ms) and end-to-end time (E2E, s), with requests pooled over "
                  f"repetitions. Rows are grouped by variant and pod session (Table~\\ref{{tab:pod-hardware}}). "
                  f"Throughput and SLOs of the same load points: Table~\\ref{{{lab}-thr}}.",
                  lab, ["scenario", "load", "$n$", "TTFT p50", "p95", "p99", "TPOT p50", "p95", "E2E p50", "p99"],
                  lat, "llrrrrrrrr")
            + table(f"Controlled: {latex_escape(title)}. Part 2 of 2, throughput and objectives. R: repetitions at "
                    "that point; aggregate: mean over repetitions of the windowed output rate (tokens/s), CV its "
                    "coefficient of variation across repetitions (- for a single repetition); SLO: initials of the "
                    "pre-registered SLOs met in every repetition. Latency of the same load points: "
                    f"Table~\\ref{{{lab}}}.",
                    f"{lab}-thr", ["scenario", "load", "R", "$n$", "aggregate tok/s", "CV\\%", "SLO"],
                    thr, "llrrrrl"))



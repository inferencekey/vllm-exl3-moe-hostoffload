"""No-fake-data registry: every number the paper prints passes through here with its source file.

- `Registry.put(key, value, sources, kind, fmt)` records a value, the files it was computed from (with sha256) and
  whether it is static, exploratory or controlled.
- `Registry.write(dir)` emits `values.tex` (one `\\dvset{key}{value}` per value), `provenance.json` (key -> value,
  sources, hashes, kind) and keeps nothing else.
- In LaTeX, `\\dv{key}` prints the value, or a visible NOT RUN marker when the key was never produced (default), or
  stops the build with an error when the paper is built with `\\strictdatatrue` (`make paper STRICT=1`).
- Generated tables that lack data are replaced by `\\notrunblock{<expected data path>}` (same strict behaviour).

A value may be put only from files that exist, and a controlled value may not come from data/exploratory.
"""
from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
KINDS = ("static", "exploratory", "controlled")
_KEY = re.compile(r"^[a-zA-Z][a-zA-Z0-9.:_-]*$")


class MissingData(FileNotFoundError):
    """Raised when an expected data file does not exist."""


def require(path: Path) -> Path:
    p = Path(path)
    if not p.exists():
        raise MissingData(str(p))
    return p


def sha256_file(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def rel(path: Path) -> str:
    p = Path(path).resolve()
    try:
        return str(p.relative_to(ROOT))
    except ValueError:
        return str(p)


def latex_escape(s: str) -> str:
    return (s.replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%").replace("$", r"\$")
            .replace("#", r"\#").replace("_", r"\_").replace("{", r"\{").replace("}", r"\}"))


@dataclass
class Entry:
    key: str
    value: object
    text: str
    kind: str
    sources: list[str]
    hashes: dict[str, str]
    note: str = ""


@dataclass
class Registry:
    entries: dict[str, Entry] = field(default_factory=dict)
    artifacts: dict[str, dict] = field(default_factory=dict)

    def put(self, key: str, value, sources: list[Path], kind: str, fmt: str = "{}", note: str = "") -> str:
        if not _KEY.match(key):
            raise ValueError(f"bad key {key!r}")
        if kind not in KINDS:
            raise ValueError(f"bad kind {kind!r}")
        if value is None:
            raise ValueError(f"{key}: refusing to register None")
        if not sources:
            raise ValueError(f"{key}: a value needs at least one source file")
        srcs = [rel(require(s)) for s in sources]
        if kind == "controlled" and any(s.startswith("data/exploratory/") for s in srcs):
            raise ValueError(f"{key}: controlled values cannot come from exploratory data")
        if kind == "exploratory" and not any(s.startswith("data/exploratory/") for s in srcs):
            raise ValueError(f"{key}: exploratory values must cite an exploratory file")
        text = fmt.format(value)
        if key in self.entries and self.entries[key].text != text:
            raise ValueError(f"{key}: registered twice with different values")
        self.entries[key] = Entry(key, value, text, kind, srcs, {s: sha256_file(ROOT / s) for s in srcs}, note)
        return text

    def artifact(self, name: str, kind: str, sources: list[Path], status: str) -> None:
        """Record a generated table or figure, its sources and whether it holds data or a NOT RUN placeholder."""
        # an artifact may only cite files that exist, like a value
        self.artifacts[name] = {"kind": kind, "status": status, "sources": [rel(require(s)) for s in sources]}

    def write(self, out_dir: Path) -> None:
        out_dir.mkdir(parents=True, exist_ok=True)
        lines = ["% Generated by hostoffload.analysis.pipeline. Do not edit. Every value cites its source in",
                 "% provenance.json."]
        for k in sorted(self.entries):
            e = self.entries[k]
            lines.append(f"\\dvset{{{k}}}{{{latex_escape(e.text)}}}% {e.kind}: {', '.join(e.sources)}")
        (out_dir / "values.tex").write_text("\n".join(lines) + "\n")
        prov = {"values": {k: {"value": e.value, "text": e.text, "kind": e.kind, "sources": e.sources,
                               "sha256": e.hashes, "note": e.note} for k, e in sorted(self.entries.items())},
                "artifacts": dict(sorted(self.artifacts.items()))}
        (out_dir / "provenance.json").write_text(json.dumps(prov, indent=1, default=str) + "\n")


def notrun_block(expected: str, what: str) -> str:
    """LaTeX for a table or figure whose data does not exist yet."""
    return f"\\notrunblock{{{latex_escape(expected)}}}{{{latex_escape(what)}}}\n"
